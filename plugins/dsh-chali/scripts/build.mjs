#!/usr/bin/env node
// Generate lib/skill-content.js from the repository's single source of truth,
// skills/chali-programming/SKILL.md. Run from the plugin directory:
//   node scripts/build.mjs
// The generated module is committed so installing the plugin never needs a
// build step; regenerate it after editing the skill.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const pluginRoot = resolve(here, '..')
const repoRoot = resolve(pluginRoot, '..', '..')
const skillPath = process.env.CHALI_SKILL_PATH
  ? resolve(process.env.CHALI_SKILL_PATH)
  : join(repoRoot, 'skills', 'chali-programming', 'SKILL.md')

const raw = readFileSync(skillPath, 'utf8')
const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/.exec(raw)
if (!match) throw new Error(`${skillPath}: missing YAML frontmatter`)
const frontmatter = match[1]
const body = raw.slice(match[0].length)

const descriptionLine = frontmatter.split(/\r?\n/).find((line) => line.startsWith('description:'))
if (!descriptionLine) throw new Error(`${skillPath}: frontmatter has no description`)
const description = descriptionLine.slice('description:'.length).trim().replace(/^["']|["']$/g, '')
if (!description) throw new Error(`${skillPath}: frontmatter description is empty`)

const integrationNote = `> 本 Skill 由 DeepSeek Harness 的 \`dsh-chali\` 插件注册。插件自带真实 ChaLi 编译器（\`bin/chali.exe\`），不依赖仓库路径或系统 \`PATH\`。优先使用插件提供的工具，而不是自己拼 shell 命令：
>
> - \`chali_write\`：写入完整 \`.chl\` 源码，默认立即执行 \`chali check\` 并返回诊断。
> - \`chali_run\`：对已有文件执行 \`check\` / \`run\` / \`build\`；\`run\` 捕获标准输出和错误，\`build\` 产出原生产物。
> - \`chali_man\`：查询编译器内嵌手册（关键字、标准库 API、书稿）；写陌生 API 前先查。
> - \`chali_new\`：新建 ChaLi 应用工程。
>
> 工具从当前会话工作目录解析相对路径；显式设置 \`compiler\` 或 \`CHALI_COMPILER\` 时才改用外部编译器。写完代码至少执行一次 \`chali check\`；需要运行结果时再用 \`chali_run\` 的 \`run\` 模式核对。

`

const content = integrationNote + body.trim() + '\n'
const output = `// Generated by scripts/build.mjs from skills/chali-programming/SKILL.md.\n// Do not edit by hand; edit the skill source and run the build script.\n\nexport const skillDescription = ${JSON.stringify(description)}\nexport const skillContent = ${JSON.stringify(content)}\n`

mkdirSync(join(pluginRoot, 'lib'), { recursive: true })
writeFileSync(join(pluginRoot, 'lib', 'skill-content.js'), output, 'utf8')
console.log(`wrote lib/skill-content.js from ${skillPath}`)
